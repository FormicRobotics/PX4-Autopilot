/**
 * Camera switch AUX channel
 *
 * RC AUX channel that selects the analog camera (PD11).
 * AUX above 0 selects camera 1, AUX at or below 0 selects camera 2.
 * Map the radio switch to the AUX channel with RC_MAP_AUXn.
 * With 0, camera 1 is selected at boot and RC is ignored.
 *
 * @value 0 Disabled, camera 1 selected
 * @value 1 AUX1
 * @value 2 AUX2
 * @value 3 AUX3
 * @value 4 AUX4
 * @value 5 AUX5
 * @value 6 AUX6
 * @min 0
 * @max 6
 * @reboot_required true
 * @group OSD
 */
PARAM_DEFINE_INT32(TBS_CAM_SWITCH, 0);
